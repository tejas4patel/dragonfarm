# The catalog: what exists (document sets and their versions, runs) and what
# happened (events). One SQLite file in the runs folder on a laptop; one
# shared Postgres database in a company, chosen with DRAGONFARM_CATALOG (a
# postgresql:// address) or options(dragonfarm.catalog = <a function that
# returns a DBI connection>). The same queries run on both. Big files
# (documents, chunks, embeddings, weights) stay in their folders; the catalog
# points at them and never changes them.
#
# Events are append-only: the database refuses updates and deletes, so the
# record of what was asked, run, approved, or refused cannot be edited.

store_schema_version <- 2L

store_ddl <- c(
  "CREATE TABLE IF NOT EXISTS meta (key TEXT PRIMARY KEY, value TEXT)",
  "CREATE TABLE IF NOT EXISTS document_sets (name TEXT PRIMARY KEY, dir TEXT NOT NULL, first_seen TEXT NOT NULL)",
  paste("CREATE TABLE IF NOT EXISTS set_versions (set_name TEXT NOT NULL, version INTEGER NOT NULL,",
        "chunks_md5 TEXT NOT NULL, reader_version INTEGER, n_sources INTEGER, n_chunks INTEGER,",
        "seen_at TEXT NOT NULL, PRIMARY KEY (set_name, version))"),
  paste("CREATE TABLE IF NOT EXISTS runs (id TEXT PRIMARY KEY, dir TEXT NOT NULL, model TEXT, method TEXT,",
        "state TEXT, created_at TEXT, updated_at TEXT NOT NULL)"),
  paste("CREATE TABLE IF NOT EXISTS events (id INTEGER PRIMARY KEY AUTOINCREMENT, at TEXT NOT NULL,",
        "actor TEXT, kind TEXT NOT NULL, name TEXT, ok INTEGER, code TEXT, detail TEXT, duration_ms INTEGER)"),
  "CREATE TABLE IF NOT EXISTS policies (version INTEGER PRIMARY KEY, body TEXT NOT NULL, set_by TEXT, set_at TEXT NOT NULL)",
  "CREATE TRIGGER IF NOT EXISTS policies_no_update BEFORE UPDATE ON policies BEGIN SELECT RAISE(ABORT, 'policy versions are append-only'); END",
  "CREATE TRIGGER IF NOT EXISTS policies_no_delete BEFORE DELETE ON policies BEGIN SELECT RAISE(ABORT, 'policy versions are append-only'); END",
  "CREATE TRIGGER IF NOT EXISTS events_no_update BEFORE UPDATE ON events BEGIN SELECT RAISE(ABORT, 'events are append-only'); END",
  "CREATE TRIGGER IF NOT EXISTS events_no_delete BEFORE DELETE ON events BEGIN SELECT RAISE(ABORT, 'events are append-only'); END",
  # Model registry (schema 2): versions and sign-offs, both append-only.
  paste("CREATE TABLE IF NOT EXISTS model_versions (name TEXT NOT NULL, version INTEGER NOT NULL, run_id TEXT NOT NULL,",
        "run_dir TEXT, base_model TEXT, revision TEXT, data_md5 TEXT, evaluation TEXT, proposed_by TEXT,",
        "proposed_at TEXT NOT NULL, PRIMARY KEY (name, version))"),
  paste("CREATE TABLE IF NOT EXISTS model_signoffs (id INTEGER PRIMARY KEY AUTOINCREMENT, name TEXT NOT NULL,",
        "version INTEGER NOT NULL, decision TEXT NOT NULL CHECK (decision IN ('approved', 'rejected', 'retired')),",
        "meaning TEXT NOT NULL, signer TEXT, signed_at TEXT NOT NULL)"),
  "CREATE TRIGGER IF NOT EXISTS model_versions_no_update BEFORE UPDATE ON model_versions BEGIN SELECT RAISE(ABORT, 'model versions are append-only'); END",
  "CREATE TRIGGER IF NOT EXISTS model_versions_no_delete BEFORE DELETE ON model_versions BEGIN SELECT RAISE(ABORT, 'model versions are append-only'); END",
  "CREATE TRIGGER IF NOT EXISTS model_signoffs_no_update BEFORE UPDATE ON model_signoffs BEGIN SELECT RAISE(ABORT, 'sign-offs are append-only'); END",
  "CREATE TRIGGER IF NOT EXISTS model_signoffs_no_delete BEFORE DELETE ON model_signoffs BEGIN SELECT RAISE(ABORT, 'sign-offs are append-only'); END"
)

# Postgres: the same tables, with identity columns, and append-only enforced
# by one trigger function that raises the table's message.
store_ddl_pg <- function() {
  ddl <- gsub("INTEGER PRIMARY KEY AUTOINCREMENT", "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY",
              store_ddl[!grepl("^CREATE TRIGGER", store_ddl)], fixed = TRUE)
  guard <- function(table, msg) {
    sprintf(paste("CREATE OR REPLACE TRIGGER %s_append_only BEFORE UPDATE OR DELETE ON %s",
                  "FOR EACH ROW EXECUTE FUNCTION dragonfarm_append_only('%s')"), table, table, msg)
  }
  c(ddl,
    paste("CREATE OR REPLACE FUNCTION dragonfarm_append_only() RETURNS trigger AS",
          "$$ BEGIN RAISE EXCEPTION '%', TG_ARGV[0]; END $$ LANGUAGE plpgsql"),
    guard("policies", "policy versions are append-only"), guard("events", "events are append-only"),
    guard("model_versions", "model versions are append-only"), guard("model_signoffs", "sign-offs are append-only"))
}

store_is_pg <- function(con) inherits(con, "PqConnection")

# Queries are written with ? placeholders; Postgres wants $1, $2, ...
store_sql <- function(con, sql) {
  if (!store_is_pg(con)) return(sql)
  m <- gregexpr("?", sql, fixed = TRUE)[[1]]
  if (m[1] == -1) return(sql)
  regmatches(sql, list(m)) <- list(paste0("$", seq_along(m)))
  sql
}

store_get <- function(con, sql, params = NULL) {
  if (is.null(params)) DBI::dbGetQuery(con, store_sql(con, sql)) else DBI::dbGetQuery(con, store_sql(con, sql), params = params)
}

store_exec <- function(con, sql, params = NULL) {
  if (is.null(params)) DBI::dbExecute(con, store_sql(con, sql)) else DBI::dbExecute(con, store_sql(con, sql), params = params)
}

# A shared catalog (Postgres in a company), if one is configured: a function
# returning a DBI connection, or a postgresql:// address.
store_shared <- function() {
  cat <- getOption("dragonfarm.catalog", Sys.getenv("DRAGONFARM_CATALOG", ""))
  if (is.function(cat)) return(cat)
  if (is.character(cat) && length(cat) == 1 && nzchar(cat)) {
    return(function() {
      rlang::check_installed("RPostgres", reason = "to use a Postgres catalog.")
      do.call(DBI::dbConnect, c(list(RPostgres::Postgres(), bigint = "integer"), pg_uri_parts(cat)))
    })
  }
  NULL
}

# postgresql://user:password@host:port/dbname -> connection arguments.
pg_uri_parts <- function(uri) {
  m <- regmatches(uri, regexec("^postgres(?:ql)?://(?:([^:@/]*)(?::([^@/]*))?@)?([^:/?]*)(?::([0-9]+))?(?:/([^?]*))?", uri, perl = TRUE))[[1]]
  if (!length(m)) cli::cli_abort("{.val {uri}} is not a postgresql:// address.", class = "dragonfarm_error", code = "INVALID_ARGUMENTS")
  parts <- list(user = m[2], password = m[3], host = m[4], port = m[5], dbname = m[6])
  parts <- lapply(parts, utils::URLdecode)
  parts[vapply(parts, nzchar, TRUE)]
}

# Open (or create) the catalog: the shared one when configured, otherwise the
# runs folder's own SQLite file; one connection each per session.
store_open <- function(runs_dir = dragon_runs_dir()) {
  if (is.null(the$stores)) the$stores <- list()
  shared <- store_shared()
  if (!is.null(shared)) {
    con <- the$stores[["<shared>"]]
    if (!is.null(con) && DBI::dbIsValid(con)) return(con)
    con <- shared()
    store_migrate(con)
    the$stores[["<shared>"]] <- con
    return(con)
  }
  # Create first, then normalise: a path that does not exist yet normalises
  # differently from the same path once it does (/var vs /private/var on
  # macOS, short 8.3 names on Windows), which would open a second connection.
  dir.create(runs_dir, recursive = TRUE, showWarnings = FALSE)
  runs_dir <- normalizePath(runs_dir, winslash = "/", mustWork = TRUE)
  con <- the$stores[[runs_dir]]
  if (!is.null(con) && DBI::dbIsValid(con)) return(con)
  con <- DBI::dbConnect(RSQLite::SQLite(), file.path(runs_dir, "dragonfarm.sqlite"))
  store_exec(con, "PRAGMA busy_timeout = 5000")
  store_migrate(con)
  the$stores[[runs_dir]] <- con
  con
}

store_close_all <- function() {
  for (con in the$stores) if (DBI::dbIsValid(con)) DBI::dbDisconnect(con)
  the$stores <- list()
  invisible(NULL)
}

store_migrate <- function(con) {
  for (sql in if (store_is_pg(con)) store_ddl_pg() else store_ddl) store_exec(con, sql)
  v <- store_get(con, "SELECT value FROM meta WHERE key = 'schema_version'")$value
  if (!length(v)) {
    store_exec(con, "INSERT INTO meta (key, value) VALUES ('schema_version', ?)", params = list(as.character(store_schema_version)))
  } else if (as.integer(v) > store_schema_version) {
    cli::cli_abort("This runs folder's catalog was written by a newer dragonfarm (schema {v}); update the package.")
  } else if (as.integer(v) < store_schema_version) {
    # The tables above were just created; record the new schema.
    store_exec(con, "UPDATE meta SET value = ? WHERE key = 'schema_version'", params = list(as.character(store_schema_version)))
  }
  invisible(con)
}

# Append one event. Never stops the work it records: a failed write returns
# FALSE with a warning.
store_record_event <- function(kind, name = NULL, ok = NA, code = NULL, detail = NULL, duration_ms = NULL,
                               runs_dir = dragon_runs_dir()) {
  tryCatch({
    con <- store_open(runs_dir)
    id <- store_get(con, paste("INSERT INTO events (at, actor, kind, name, ok, code, detail, duration_ms)",
                               "VALUES (?, ?, ?, ?, ?, ?, ?, ?) RETURNING id"),
                    params = list(now_utc(), current_user(), kind, name %||% NA_character_,
                                  if (is.na(ok)) NA_integer_ else as.integer(ok), code %||% NA_character_,
                                  if (is.null(detail)) NA_character_ else as.character(jsonlite::toJSON(detail, auto_unbox = TRUE, null = "null")),
                                  if (is.null(duration_ms)) NA_integer_ else as.integer(duration_ms)))$id
    invisible(as.integer(id))
  }, error = function(e) {
    cli::cli_warn("Could not record an event in the catalog: {conditionMessage(e)}")
    invisible(NA_integer_)
  })
}

store_events <- function(limit = 100L, kind = NULL, runs_dir = dragon_runs_dir()) {
  con <- store_open(runs_dir)
  if (is.null(kind)) {
    store_get(con, "SELECT * FROM events ORDER BY id DESC LIMIT ?", params = list(as.integer(limit)))
  } else {
    store_get(con, "SELECT * FROM events WHERE kind = ? ORDER BY id DESC LIMIT ?", params = list(kind, as.integer(limit)))
  }
}

# Bring the catalog up to date with the folders: document sets get a new
# version whenever their chunks change (old versions are kept), runs are
# added or their state refreshed. Reads the folders; never writes to them.
store_sync <- function(runs_dir = dragon_runs_dir()) {
  con <- store_open(runs_dir)
  sets <- dragon_documents_list(runs_dir)
  new_versions <- 0L
  for (i in seq_len(nrow(sets))) {
    if (store_sync_set(con, sets$name[i], sets$dir[i])) new_versions <- new_versions + 1L
  }
  runs <- dragon_runs(runs_dir)
  for (i in seq_len(nrow(runs))) {
    store_exec(con, paste("INSERT INTO runs (id, dir, model, method, state, created_at, updated_at) VALUES (?, ?, ?, ?, ?, ?, ?)",
                              "ON CONFLICT(id) DO UPDATE SET state = excluded.state, updated_at = excluded.updated_at"),
                   params = list(runs$id[i], runs$dir[i], runs$model[i] %||% NA_character_, runs$method[i] %||% NA_character_,
                                 runs$state[i] %||% NA_character_, runs$created_at[i] %||% NA_character_, now_utc()))
  }
  invisible(list(sets = nrow(sets), new_versions = new_versions, runs = nrow(runs)))
}

store_sync_set <- function(con, name, dir) {
  chunks <- file.path(dir, "chunks.jsonl")
  if (!file.exists(chunks)) return(FALSE)
  md5 <- unname(tools::md5sum(chunks))
  store_exec(con, "INSERT INTO document_sets (name, dir, first_seen) VALUES (?, ?, ?) ON CONFLICT(name) DO NOTHING",
                 params = list(name, normalizePath(dir, winslash = "/"), now_utc()))
  last <- store_get(con, "SELECT version, chunks_md5 FROM set_versions WHERE set_name = ? ORDER BY version DESC LIMIT 1",
                          params = list(name))
  if (nrow(last) && identical(last$chunks_md5[1], md5)) return(FALSE)
  m <- read_json(file.path(dir, "manifest.json"))
  store_exec(con, paste("INSERT INTO set_versions (set_name, version, chunks_md5, reader_version, n_sources, n_chunks, seen_at)",
                            "VALUES (?, ?, ?, ?, ?, ?, ?)"),
                 params = list(name, if (nrow(last)) last$version[1] + 1L else 1L, md5,
                               as.integer(m$chunking$reader %||% NA_integer_), length(m$sources),
                               as.integer(m$n_chunks %||% NA_integer_), now_utc()))
  TRUE
}

now_utc <- function() format(Sys.time(), "%Y-%m-%dT%H:%M:%SZ", tz = "UTC")

# The whole record as a file for an auditor: every event, oldest first, as
# CSV, with the export itself recorded (row count and a SHA-256 of the file)
# so a copy can be shown to match what was exported.
store_export <- function(file, since = NULL, runs_dir = dragon_runs_dir()) {
  con <- store_open(runs_dir)
  ev <- if (is.null(since)) store_get(con, "SELECT * FROM events ORDER BY id")
        else store_get(con, "SELECT * FROM events WHERE at >= ? ORDER BY id", params = list(as.character(since)))
  utils::write.csv(ev, file, row.names = FALSE, na = "", fileEncoding = "UTF-8")
  sha <- digest_sha256(file)
  store_record_event("record_export", basename(file), ok = TRUE,
                     detail = list(rows = nrow(ev), since = since, sha256 = sha), runs_dir = runs_dir)
  invisible(list(file = file, rows = nrow(ev), sha256 = sha))
}

digest_sha256 <- function(file) {
  if (requireNamespace("openssl", quietly = TRUE)) {
    return(paste(sprintf("%02x", as.integer(unclass(openssl::sha256(file(file))))), collapse = ""))
  }
  unname(tools::md5sum(file))   # without openssl: MD5, which still shows a copy is unchanged
}

# What happened recently, for an admin: events by kind, refusals and
# failures by code, outbound calls by host, approvals still waiting. From the
# record only; nothing is stored twice.
store_summary <- function(days = 7, runs_dir = dragon_runs_dir()) {
  con <- store_open(runs_dir)
  since <- format(Sys.time() - days * 86400, "%Y-%m-%dT%H:%M:%SZ", tz = "UTC")
  ev <- store_get(con, "SELECT kind, name, ok, code, detail FROM events WHERE at >= ?", params = list(since))
  bytes <- vapply(ev$detail[ev$kind == "outbound"], function(d) {
    b <- tryCatch(jsonlite::fromJSON(d)$bytes, error = function(e) NULL)
    if (is.numeric(b) && length(b) == 1 && !is.na(b)) b else 0
  }, 0)
  out <- ev[ev$kind == "outbound", , drop = FALSE]
  list(
    days = days,
    kinds = sort(table(ev$kind), decreasing = TRUE),
    problems = sort(table(ev$code[!is.na(ev$code) & nzchar(ev$code)]), decreasing = TRUE),
    outbound = if (nrow(out)) stats::aggregate(list(calls = rep(1L, nrow(out)), bytes = unname(bytes)),
                                               by = list(host = out$name), FUN = sum) else data.frame(host = character(), calls = integer(), bytes = numeric()),
    waiting = nrow(approvals_pending(runs_dir)),
    agents = agent_fallback_rate(days, runs_dir)
  )
}
